from __future__ import annotations

import hashlib
import hmac
import re
import secrets
import uuid
from datetime import datetime, timedelta, timezone
from typing import Any, Optional

from .access_keys import new_access_key
from .audit import append_audit, audit_actor
from .store import Store
from .sync_queue import enqueue_access_key
from .user_ids import new_user_id


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _matches(item: dict[str, Any], reference: str) -> bool:
    numeric_reference = reference[1:] if reference.startswith("#") else reference
    if numeric_reference.isdecimal():
        return str(item.get("numeric_id", "")) == numeric_reference
    return (
        item["id"].casefold() == reference.casefold()
        or item["name"].casefold() == reference.casefold()
        or item.get("alias", "").casefold() == reference.casefold()
    )


class UserService:
    def __init__(self, store: Store) -> None:
        self.store = store

    @staticmethod
    def _actor(explicit: Optional[str] = None) -> str:
        return audit_actor(explicit)

    @staticmethod
    def _audit(
        data: dict[str, Any],
        *,
        actor: str,
        action: str,
        user_id: str,
        fields: list[str],
    ) -> None:
        append_audit(data, actor=actor, action=action, object_type="user",
                     object_id=user_id, fields=fields)

    def create(self, name: str) -> tuple[dict[str, Any], str]:
        name = name.strip()
        if not name or len(name) > 64 or any(ord(char) < 32 for char in name):
            raise ValueError("invalid_name")
        with self.store.transaction() as data:
            if any(item["name"].casefold() == name.casefold() for item in data["users"]):
                raise ValueError("duplicate_name")
            timestamp = _now()
            existing_ids = {str(item["id"]) for item in data["users"]}
            numeric_id = data.setdefault("settings", {}).setdefault(
                "next_user_numeric_id", 1
            )
            if not isinstance(numeric_id, int) or isinstance(numeric_id, bool) or numeric_id < 1:
                raise RuntimeError("invalid next user numeric id")
            used_numbers = {item.get("numeric_id") for item in data["users"]}
            while numeric_id in used_numbers:
                numeric_id += 1
            user = {
                "id": new_user_id(existing_ids),
                "numeric_id": numeric_id,
                "name": name,
                "enabled": True,
                "created_at": timestamp,
                "updated_at": timestamp,
                "subscription_state": "active",
            }
            data["settings"]["next_user_numeric_id"] = numeric_id + 1
            token, credential = self._new_subscription_credential(user["id"], timestamp)
            data["users"].append(user)
            data.setdefault("subscription_credentials", []).append(credential)
            key = new_access_key(user["id"])
            data["access_keys"].append(key)
            enqueue_access_key(data, key)
            self._audit(data, actor=self._actor(), action="user.create",
                        user_id=user["id"], fields=["name", "enabled"])
        return user, token

    @staticmethod
    def _new_subscription_credential(
        user_id: str, timestamp: Optional[str] = None
    ) -> tuple[str, dict[str, Any]]:
        token = f"{user_id}.{secrets.token_urlsafe(32)}"
        salt = secrets.token_bytes(16)
        # The token contains 256 bits generated by secrets.token_urlsafe. Unlike
        # a user password it cannot be brute-forced from a low-entropy space, so
        # a fast salted digest is both safe and avoids delaying every user create.
        digest = hashlib.sha256(salt + token.encode()).digest()
        now = timestamp or _now()
        return token, {
            "user_id": user_id,
            "algorithm": "sha256-v1",
            "salt": salt.hex(),
            "digest": digest.hex(),
            "created_at": now,
            "updated_at": now,
            "revoked_at": None,
        }

    @staticmethod
    def _matches_subscription_token(credential: dict[str, Any], token: str) -> bool:
        if credential.get("revoked_at"):
            return False
        if credential.get("algorithm") == "sha256-legacy":
            actual = hashlib.sha256(token.encode()).hexdigest()
        elif credential.get("algorithm") == "sha256-v1":
            try:
                salt = bytes.fromhex(credential["salt"])
            except (KeyError, ValueError):
                return False
            actual = hashlib.sha256(salt + token.encode()).hexdigest()
        elif credential.get("algorithm") == "scrypt-v1":
            try:
                salt = bytes.fromhex(credential["salt"])
            except (KeyError, ValueError):
                return False
            actual = hashlib.scrypt(
                token.encode(), salt=salt, n=2**14, r=8, p=1, dklen=32
            ).hex()
        else:
            return False
        return hmac.compare_digest(actual, str(credential.get("digest", "")))

    def verify_subscription_token(self, token: str) -> Optional[dict[str, Any]]:
        if not token or len(token) > 256:
            return None
        data = self.store.load()
        user_id, separator, _secret = token.partition(".")
        credentials = data.get("subscription_credentials", [])
        if separator:
            user_id_digest = hashlib.sha256(user_id.encode()).hexdigest()
            credentials = [
                item for item in credentials
                if item["user_id"] == user_id
                or hmac.compare_digest(
                    str(item.get("token_user_id_digest", "")), user_id_digest
                )
            ]
        for credential in credentials:
            if self._matches_subscription_token(credential, token):
                user = next(
                    (item for item in data["users"] if item["id"] == credential["user_id"]),
                    None,
                )
                if user and user.get("enabled", True) and user.get("subscription_state") == "active":
                    return user
        return None

    def rotate_subscription(self, reference: str, actor: Optional[str] = None) -> tuple[dict[str, Any], str]:
        return self._replace_subscription(reference, actor, "subscription.rotate")

    def create_subscription(self, reference: str, actor: Optional[str] = None) -> tuple[dict[str, Any], str]:
        data = self.store.load()
        user = next((item for item in data["users"] if _matches(item, reference)), None)
        if user is None:
            raise ValueError("user_not_found")
        active = any(
            item["user_id"] == user["id"] and not item.get("revoked_at")
            for item in data.get("subscription_credentials", [])
        )
        if active and user.get("subscription_state", "active") == "active":
            raise ValueError("subscription_exists")
        return self._replace_subscription(reference, actor, "subscription.create")

    def _replace_subscription(
        self, reference: str, actor: Optional[str], action: str
    ) -> tuple[dict[str, Any], str]:
        data = self.store.load()
        user = next((item for item in data["users"] if _matches(item, reference)), None)
        if user is None:
            raise ValueError("user_not_found")
        timestamp = _now()
        token, credential = self._new_subscription_credential(user["id"], timestamp)
        data["subscription_credentials"] = [
            item for item in data.get("subscription_credentials", []) if item["user_id"] != user["id"]
        ]
        data["subscription_credentials"].append(credential)
        user["subscription_state"] = "active"
        user["updated_at"] = timestamp
        self._audit(
            data,
            actor=self._actor(actor),
            action=action,
            user_id=user["id"],
            fields=["subscription_token"],
        )
        self.store.save(data)
        return user, token

    def revoke_subscription(self, reference: str, actor: Optional[str] = None) -> dict[str, Any]:
        data = self.store.load()
        user = next((item for item in data["users"] if _matches(item, reference)), None)
        if user is None:
            raise ValueError("user_not_found")
        timestamp = _now()
        for credential in data.get("subscription_credentials", []):
            if credential["user_id"] == user["id"] and not credential.get("revoked_at"):
                credential["revoked_at"] = timestamp
                credential["updated_at"] = timestamp
        user["subscription_state"] = "revoked"
        user["updated_at"] = timestamp
        self._audit(
            data,
            actor=self._actor(actor),
            action="subscription.revoke",
            user_id=user["id"],
            fields=["subscription_state"],
        )
        self.store.save(data)
        return user

    def subscription_status(self, reference: str) -> dict[str, Any]:
        user = self.find(reference)
        return {
            "user_id": user["id"],
            "state": user.get("subscription_state", "active"),
            "enabled": user.get("enabled", True),
        }

    def list(self) -> list[dict[str, Any]]:
        return list(self.store.load()["users"])

    def find(self, reference: str) -> dict[str, Any]:
        matches = [
            item
            for item in self.list()
            if _matches(item, reference)
        ]
        if len(matches) != 1:
            raise ValueError("user_not_found")
        return matches[0]

    def set_enabled(self, reference: str, enabled: bool) -> dict[str, Any]:
        with self.store.transaction() as data:
            user = next((item for item in data["users"] if _matches(item, reference)), None)
            if user is None:
                raise ValueError("user_not_found")
            if enabled and any(item["user_id"] == user["id"] and item.get("state") != "purged"
                               for item in data.get("user_deletions", [])):
                raise ValueError("user_deletion_in_progress")
            timestamp = _now()
            user["enabled"] = enabled
            user["updated_at"] = timestamp
            affected = []
            for key in data.get("access_keys", []):
                if key["user_id"] != user["id"] or key["state"] == "revoked":
                    continue
                if not enabled:
                    key["state_before_user_disable"] = key["state"]
                    key["state"] = "disabled"
                    key["disabled_reason"] = "user_disabled"
                elif key.get("disabled_reason") == "user_disabled":
                    key["state"] = key.pop("state_before_user_disable", "active")
                    key["disabled_reason"] = None if key["state"] == "active" else key.get("disabled_reason")
                else:
                    continue
                key["updated_at"] = timestamp
                enqueue_access_key(data, key)
                affected.append(key["id"])
            self._audit(data, actor=self._actor(),
                        action="user.enable" if enabled else "user.disable",
                        user_id=user["id"], fields=["enabled", "access_keys"])
            return user

    def rename(self, reference: str, new_name: str) -> dict[str, Any]:
        new_name = new_name.strip()
        if not new_name or len(new_name) > 64 or any(ord(char) < 32 for char in new_name):
            raise ValueError("invalid_name")
        data = self.store.load()
        if any(
            item["name"].casefold() == new_name.casefold()
            and item["id"] != reference
            and item["name"].casefold() != reference.casefold()
            for item in data["users"]
        ):
            raise ValueError("duplicate_name")
        for item in data["users"]:
            if _matches(item, reference):
                if item["name"] != new_name:
                    item.setdefault("previous_names", []).append(
                        {"name": item["name"], "changed_at": _now()}
                    )
                    item["name"] = new_name
                    item["updated_at"] = _now()
                    self._audit(data, actor=self._actor(), action="user.rename",
                                user_id=item["id"], fields=["name"])
                    self.store.save(data)
                return item
        raise ValueError("user_not_found")

    def set_metadata(
        self,
        reference: str,
        *,
        note: Optional[str] = None,
        tags: Optional[list[str]] = None,
        actor: Optional[str] = None,
    ) -> dict[str, Any]:
        if note is not None and len(note) > 1000:
            raise ValueError("invalid_note")
        if tags is not None:
            tags = sorted({tag.strip() for tag in tags if tag.strip()})
            if len(tags) > 32 or any(len(tag) > 64 for tag in tags):
                raise ValueError("invalid_tags")
        data = self.store.load()
        for item in data["users"]:
            if _matches(item, reference):
                changed_fields = []
                if note is not None:
                    item["note"] = note
                    changed_fields.append("note")
                if tags is not None:
                    item["tags"] = tags
                    changed_fields.append("tags")
                timestamp = _now()
                item["updated_at"] = timestamp
                item["metadata_updated_at"] = timestamp
                item["metadata_updated_by"] = self._actor(actor)
                self._audit(
                    data,
                    actor=item["metadata_updated_by"],
                    action="user.metadata.update",
                    user_id=item["id"],
                    fields=changed_fields,
                )
                self.store.save(data)
                return item
        raise ValueError("user_not_found")

    def set_admin_metadata(
        self,
        reference: str,
        *,
        contact: Optional[str] = None,
        source: Optional[str] = None,
        external_id: Optional[str] = None,
        attributes: Optional[dict[str, str]] = None,
        clear_attributes: bool = False,
        actor: Optional[str] = None,
    ) -> dict[str, Any]:
        scalar_values = {"contact": contact, "source": source, "external_id": external_id}
        if any(value is not None and len(value) > 256 for value in scalar_values.values()):
            raise ValueError("invalid_admin_metadata")
        if attributes is not None:
            if len(attributes) > 32 or any(
                not re.fullmatch(r"[A-Za-z0-9._-]{1,64}", key) or len(value) > 512
                for key, value in attributes.items()
            ):
                raise ValueError("invalid_admin_metadata")
        data = self.store.load()
        for item in data["users"]:
            if _matches(item, reference):
                changed_fields = []
                admin = item.setdefault("admin", {})
                for field, value in scalar_values.items():
                    if value is not None:
                        admin[field] = value or None
                        changed_fields.append(field)
                if clear_attributes:
                    admin["attributes"] = {}
                    changed_fields.append("attributes")
                if attributes:
                    admin.setdefault("attributes", {}).update(attributes)
                    changed_fields.append("attributes")
                if not changed_fields:
                    raise ValueError("admin_metadata_empty")
                timestamp = _now()
                audit_actor = self._actor(actor)
                item["updated_at"] = timestamp
                item["metadata_updated_at"] = timestamp
                item["metadata_updated_by"] = audit_actor
                self._audit(
                    data,
                    actor=audit_actor,
                    action="user.admin_metadata.update",
                    user_id=item["id"],
                    fields=changed_fields,
                )
                self.store.save(data)
                return item
        raise ValueError("user_not_found")

    def audit_log(self, limit: int = 100) -> list[dict[str, Any]]:
        if not 1 <= limit <= 1000:
            raise ValueError("invalid_audit_limit")
        return list(reversed(self.store.load().get("audit_log", [])[-limit:]))

    def set_alias(self, reference: str, alias: str) -> dict[str, Any]:
        alias = alias.strip()
        if alias and not re.fullmatch(r"[A-Za-z0-9._-]{1,64}", alias):
            raise ValueError("invalid_alias")
        data = self.store.load()
        target = next(
            (
                item
                for item in data["users"]
                if _matches(item, reference)
            ),
            None,
        )
        if target is None:
            raise ValueError("user_not_found")
        if alias and any(
            item["id"] != target["id"]
            and item.get("alias", "").casefold() == alias.casefold()
            for item in data["users"]
        ):
            raise ValueError("duplicate_alias")
        target["alias"] = alias or None
        target["updated_at"] = _now()
        self._audit(data, actor=self._actor(), action="user.alias.update",
                    user_id=target["id"], fields=["alias"])
        self.store.save(data)
        return target

    def delete_plan(self, reference: str, grace_seconds: int = 86400) -> dict[str, Any]:
        if not 0 <= grace_seconds <= 365 * 86400:
            raise ValueError("user_invalid_grace")
        data = self.store.load()
        user = next((item for item in data["users"] if _matches(item, reference)), None)
        if user is None:
            raise ValueError("user_not_found")
        keys = [item for item in data.get("access_keys", []) if item["user_id"] == user["id"]]
        nodes = [item for item in data.get("nodes", []) if item.get("enabled", True)]
        return {
            "user_id": user["id"], "name": user["name"], "grace_seconds": grace_seconds,
            "access_keys": len(keys), "active_nodes": [item["id"] for item in nodes],
            "effects": ["disable_user", "disable_access_keys", "revoke_subscription",
                        "wait_for_node_ack", "destroy_credentials_after_grace"],
        }

    def request_delete(
        self, reference: str, grace_seconds: int = 86400, actor: Optional[str] = None
    ) -> dict[str, Any]:
        if not 0 <= grace_seconds <= 365 * 86400:
            raise ValueError("user_invalid_grace")
        with self.store.transaction() as data:
            user = next((item for item in data["users"] if _matches(item, reference)), None)
            if user is None:
                raise ValueError("user_not_found")
            existing = next((item for item in data.get("user_deletions", [])
                             if item["user_id"] == user["id"] and item.get("state") != "purged"), None)
            if existing:
                return existing
            now = datetime.now(timezone.utc)
            timestamp = now.isoformat()
            user["enabled"] = False
            user["subscription_state"] = "revoked"
            user["updated_at"] = timestamp
            for credential in data.get("subscription_credentials", []):
                if credential["user_id"] == user["id"] and not credential.get("revoked_at"):
                    credential["revoked_at"] = timestamp
                    credential["updated_at"] = timestamp
            operation_ids = []
            key_ids = []
            for key in data.get("access_keys", []):
                if key["user_id"] != user["id"]:
                    continue
                key_ids.append(key["id"])
                if key["state"] != "revoked":
                    key["state_before_user_disable"] = key["state"]
                    key["state"] = "disabled"
                    key["disabled_reason"] = "user_delete"
                    key["updated_at"] = timestamp
                    operation_ids.extend(item["id"] for item in enqueue_access_key(data, key))
            deletion = {
                "id": str(uuid.uuid4()), "user_id": user["id"],
                "state": "blocking", "requested_at": timestamp,
                "grace_until": (now + timedelta(seconds=grace_seconds)).isoformat(),
                "key_ids": key_ids, "operation_ids": operation_ids,
                "required_node_ids": [item["id"] for item in data.get("nodes", [])
                                      if item.get("enabled", True)],
                "confirmed_node_ids": [], "blocked_at": None, "purged_at": None,
            }
            data.setdefault("user_deletions", []).append(deletion)
            self._audit(data, actor=self._actor(actor), action="user.delete.request",
                        user_id=user["id"], fields=["enabled", "access_keys",
                                                    "subscription_state", "grace_until"])
            return deletion

    @staticmethod
    def _refresh_deletion(data: dict[str, Any], deletion: dict[str, Any]) -> dict[str, Any]:
        operations = {item["id"]: item for item in data.get("node_operations", [])}
        by_node: dict[str, list[dict[str, Any]]] = {}
        missing = False
        for operation_id in deletion.get("operation_ids", []):
            operation = operations.get(operation_id)
            if operation is None:
                missing = True
                continue
            by_node.setdefault(operation["node_id"], []).append(operation)
        confirmed = sorted(node_id for node_id in deletion.get("required_node_ids", [])
                           if by_node.get(node_id) and
                           all(item["state"] == "applied" for item in by_node[node_id]))
        if not deletion.get("required_node_ids"):
            confirmed = []
        deletion["confirmed_node_ids"] = confirmed
        all_confirmed = not missing and set(confirmed) == set(deletion.get("required_node_ids", []))
        now = datetime.now(timezone.utc)
        if all_confirmed:
            deletion["blocked_at"] = deletion.get("blocked_at") or now.isoformat()
            deletion["state"] = (
                "ready_to_purge"
                if now >= datetime.fromisoformat(deletion["grace_until"])
                else "waiting_grace"
            )
        else:
            deletion["state"] = "blocking"
        deletion["nodes"] = {
            node_id: ("confirmed" if node_id in confirmed else "pending")
            for node_id in deletion.get("required_node_ids", [])
        }
        return deletion

    def deletion_status(self, reference: str) -> dict[str, Any]:
        with self.store.transaction() as data:
            user = next((item for item in data["users"] if _matches(item, reference)), None)
            user_id = user["id"] if user else reference
            deletion = next((item for item in reversed(data.get("user_deletions", []))
                             if item["user_id"] == user_id), None)
            if deletion is None:
                raise ValueError("user_deletion_not_found")
            return self._refresh_deletion(data, deletion)

    def purge(self, reference: str, actor: Optional[str] = None) -> dict[str, Any]:
        with self.store.transaction() as data:
            user = next((item for item in data["users"] if _matches(item, reference)), None)
            user_id = user["id"] if user else reference
            deletion = next((item for item in reversed(data.get("user_deletions", []))
                             if item["user_id"] == user_id), None)
            if deletion is None:
                raise ValueError("user_deletion_not_found")
            self._refresh_deletion(data, deletion)
            if deletion["state"] != "ready_to_purge":
                raise ValueError("user_deletion_not_ready")
            key_ids = set(deletion.get("key_ids", []))
            data["users"] = [item for item in data["users"] if item["id"] != user_id]
            data["access_keys"] = [item for item in data.get("access_keys", [])
                                   if item["id"] not in key_ids]
            data["subscription_credentials"] = [
                item for item in data.get("subscription_credentials", [])
                if item["user_id"] != user_id
            ]
            data["usage_events"] = [item for item in data.get("usage_events", [])
                                    if item.get("key_id") not in key_ids]
            data["ip_observations"] = [item for item in data.get("ip_observations", [])
                                       if item.get("key_id") not in key_ids]
            data["node_operations"] = [item for item in data.get("node_operations", [])
                                       if item.get("owner_id") != user_id]
            deletion["state"] = "purged"
            deletion["purged_at"] = _now()
            deletion.pop("key_ids", None)
            deletion.pop("operation_ids", None)
            self._audit(data, actor=self._actor(actor), action="user.delete.purge",
                        user_id=user_id, fields=["credentials", "access_keys", "usage"])
            return deletion

    def search(self, query: str) -> list[dict[str, Any]]:
        needle = query.strip().casefold()
        if not needle:
            return self.list()
        matches = []
        for item in self.list():
            fields = [item["id"], item.get("numeric_id", ""),
                      f"#{item.get('numeric_id', '')}", item["name"],
                      item.get("alias", ""), item.get("note", "")]
            fields.extend(item.get("tags", []))
            fields.extend(entry.get("name", "") for entry in item.get("previous_names", []))
            if any(needle in str(field).casefold() for field in fields):
                matches.append(item)
        return matches

    def set_endpoint(self, reference: str, protocol: str, endpoint: dict[str, Any]) -> dict[str, Any]:
        data = self.store.load()
        for item in data["users"]:
            if _matches(item, reference):
                item.setdefault("endpoints", {})[protocol] = endpoint
                item["updated_at"] = _now()
                self.store.save(data)
                return item
        raise ValueError("user_not_found")
